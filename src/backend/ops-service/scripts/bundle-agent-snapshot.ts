/* Writes src/services/agent/bundled.ts from the local llm-orchestrator checkout. */
import { writeFileSync } from 'fs';
import { join } from 'path';
import { loadAgentSnapshot, loadPromptsSnapshot } from '../src/services/agent';

const payload = { agent: loadAgentSnapshot(), prompts: loadPromptsSnapshot() };
const file = join(__dirname, '../src/services/agent/bundled.ts');
writeFileSync(
  file,
  `/* GENERATED by scripts/bundle-agent-snapshot.ts at ${new Date().toISOString()} — do not commit. */\n` +
    "import type { AgentSnapshot, PromptsSnapshot } from './index';\n\n" +
    `export const BUNDLED_AGENT: { agent: AgentSnapshot; prompts: PromptsSnapshot } | null = ${JSON.stringify(payload)};\n`,
);
console.log(`bundled agent snapshot: tools=${payload.agent.tool_count} prompts=${payload.prompts.prompts.length}`);
