#!/usr/bin/env python3
"""Seed Config/Local.xcconfig from the RN driver-app .env without printing any value.

Usage: python3 scripts/seed-local-config.py [path/to/driver-app/.env]
Only key names are reported. xcconfig treats `//` as a comment, so URLs are
written as `http:/$()/host` which Xcode expands back to `http://host`.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_ENV = os.path.join(ROOT, "..", "..", "driver-app", ".env")
MAPPING = {
    "EXPO_PUBLIC_TRIP_SERVICE_URL": "TRIP_SERVICE_URL",
    "EXPO_PUBLIC_EXTERNAL_API_SERVICE_URL": "TRIP_SERVICE_URL",
    "EXPO_PUBLIC_AUTH_SERVICE_URL": "AUTH_SERVICE_URL",
    "EXPO_PUBLIC_IDENTITY_SERVICE_URL": "AUTH_SERVICE_URL",
    "EXPO_PUBLIC_TRIP_SERVICE_WS_URL": "TRIP_SERVICE_WS_URL",
    "EXPO_PUBLIC_GOONG_MAPS_KEY": "GOONG_MAPS_KEY",
}


def main() -> int:
    env_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_ENV
    values: dict[str, str] = {}
    with open(env_path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, val = line.split("=", 1)
            key = key.strip()
            val = val.strip().strip('"').strip("'")
            if key in MAPPING and val:
                values[MAPPING[key]] = val.replace("//", "/$()/")
    out = os.path.join(ROOT, "Config", "Local.xcconfig")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by scripts/seed-local-config.py — DO NOT COMMIT.\n")
        for key in ("TRIP_SERVICE_URL", "AUTH_SERVICE_URL", "TRIP_SERVICE_WS_URL", "GOONG_MAPS_KEY"):
            fh.write(f"{key} = {values.get(key, '')}\n")
    os.chmod(out, 0o600)
    print("wrote Config/Local.xcconfig with keys:", ", ".join(sorted(values)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
