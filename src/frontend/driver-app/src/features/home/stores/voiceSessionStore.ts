/** LLM sometimes speaks a bare tool id — hide from chat bubbles. */
function isRawToolToken(text: string): boolean {
  const token = text.trim();
  if (!token || /\s/.test(token)) return false;
  return /^[a-z][a-z0-9_]+$/.test(token) && token.includes("_");
}

let foregroundServiceRegistered = false;

function ensureForegroundServiceRegistered() {
  if (Platform.OS !== "android" || foregroundServiceRegistered) return;
  getForegroundService().register({
    config: {
      alert: false,
      onServiceErrorCallBack: () =>
        console.error("[voice-session] foreground service error"),
    },
  });
  foregroundServiceRegistered = true;
}

// Keeps the call connected while the driver switches to another app — Android
// suspends background network/audio for normal apps, but an active foreground
// service (with a visible notification, required by Android) is exempt.
// `ServiceType` is missing from the package's bundled .d.ts even though the
// native module requires it — cast around that one gap. `icon` must name a
// resource that actually exists in android/app/src/main/res — the package's
// own default ("ic_notification") isn't generated by Expo, which makes the
// notification invalid and startForeground() throw with no usable message.
async function startCallForegroundService() {
  if (Platform.OS !== "android") return;
  ensureForegroundServiceRegistered();
  await getForegroundService().start({
    id: 4471,
    title: "Czen Driver",
    message: "Đang trong cuộc gọi với trợ lý AI",
    ServiceType: "microphone",
    icon: "ic_launcher",
  } as any);
}

function stopCallForegroundService() {
  if (Platform.OS !== "android") return;
  // @supersami/rn-foreground-service tracks one Android service for the
  // whole app, not one per feature — this same service is what wake-word
  // listening runs under too (see wakeWordService.ts's
  // ensureForegroundServiceForListening). Stopping it here whenever a call
  // ends would also kill hands-free listening the instant "Trợ lý rảnh tay"
  // is on, even though nothing asked for it to turn off — the toggle itself
  // is meant to be the only thing that can do that. So skip the actual
  // stop() while hands-free is enabled; wake-word's own resume logic reuses
  // (and re-labels) the still-running service instead of it ever having
  // stopped.
  if (useWakeWordSettingsStore.getState().enabled) return;
  getForegroundService().stop();
}

export type VoiceSessionStatus = "idle" | "connecting" | "connected" | "error";
export type VoiceMessageSource = "user" | "agent" | "customer";
export type VoiceTranscriptMeta = {
  isFinal: boolean;
  segmentId?: string;
};

export type VoiceMessageListener = (
  text: string,
  from: VoiceMessageSource,
  meta: VoiceTranscriptMeta,
) => void;

const CHAT_TOPIC = "lk.chat";
const TRANSCRIPTION_TOPIC = "lk.transcription";
const TRANSCRIPTION_FINAL_ATTR = "lk.transcription_final";
const SEGMENT_ID_ATTR = "lk.segment_id";

function transcriptDedupKey(from: VoiceMessageSource, text: string): string {
  return `${from}:${text
    .trim()
    .replace(/\s+/g, " ")
    .replace(/[.!?…]+$/u, "")
    .toLowerCase()}`;
}

// LiveKit agents publish each STT/TTS hypothesis as a text stream on
// `lk.transcription`. Interim chunks share `lk.segment_id`; `lk.transcription_final`
// flips "false" → "true" on the trailer (only reliable after the iterator ends).
// Chat (`lk.chat`) has no such flag and is always committed.
function isFinalTranscriptStream(reader: {
  info: { topic: string; attributes?: Record<string, string> };
}): boolean {
  if (reader.info.topic !== TRANSCRIPTION_TOPIC) return true;
  return reader.info.attributes?.[TRANSCRIPTION_FINAL_ATTR] !== "false";
}

// Module-level (not React state) so the LiveKit session survives navigation
// between tabs — only the store's `status` needs to be reactive.
let room: Room | null = null;
// Set synchronously at the very top of connectWithToken(), before any
// `await` — the `room`-based staleness check further down only protects
// against a call landing *after* a previous one already assigned `room`;
// two calls close enough together (e.g. wake-word's own retry firing while
// the first attempt is still awaiting a token/room.disconnect()) can both
// race past that check before either has set `room` yet, each creating its
// own competing Room/RTCPeerConnection. Confirmed in production logs as
// overlapping peer connections and a WebRTC "Local fingerprint does not
// match identity" failure.
let connecting = false;
/** Play disconnect MP3 after LiveKit audio session is released (user hang-up). */
let pendingUserDisconnectFiller = false;
/**
 * User tapped Trợ lý to hang up — close chat + return home on idle.
 * Silence timeout / remote drop leaves the chat open so orb can reconnect.
 */
let pendingClosePanelOnIdle = false;
const audioEls = new Set<HTMLAudioElement>();
const messageListeners = new Set<VoiceMessageListener>();

// Polls the room's own connection state while `status` claims 'connected',
// as a fallback for cases where `RoomEvent.Disconnected` never fires at all
// — e.g. a data channel (the "publisher data channel ... closed
// unexpectedly" error some drivers see) dying without the underlying room
// connection itself being torn down cleanly. Without this, `status` gets
// stuck at 'connected' forever in that case: wake-word's own resume logic
// only watches for `status === 'idle'`, so a disconnect that never properly
// reports itself would permanently block hands-free listening from ever
// restarting, even though the driver's toggle is still on.
let watchdogTimer: ReturnType<typeof setInterval> | null = null;
const WATCHDOG_INTERVAL_MS = 4000;

function clearWatchdog() {
  if (watchdogTimer) {
    clearInterval(watchdogTimer);
    watchdogTimer = null;
  }
}

interface VoiceSessionState {
  status: VoiceSessionStatus;
  /** Smoothed 0..1 audio level of the AI agent's voice track, from LiveKit's ActiveSpeakersChanged — 0 when silent/not connected. */
  agentAudioLevel: number;
  /**
   * True while the backend's own agent_state_changed reports "speaking" or
   * "thinking" — unlike agentAudioLevel, this stays true through a natural
   * mid-sentence pause (no audio, but the AI hasn't finished replying yet),
   * so the assistant orb can keep moving for the AI's whole turn instead of
   * stalling every time its voice briefly drops out. See backend's
   * agent_state.py.
   */
  agentSpeaking: boolean;
  /**
   * True while the voice-agent backend reports a real SIP-dialed phone call
   * in progress (bridge, agent-mediated, or background call — see backend's
   * call_state.py). The Home mic button must not be able to hang up while
   * this is true; only the underlying phone call ending (which the backend
   * reports by publishing `active: false`) may end the session.
   */
  isCallActive: boolean;
  /** In-room SIP sub-call mode from backend call_state — agent or bridge. */
  callMode: "" | "agent" | "bridge";
  /**
   * True when the driver's microphone is off but the LiveKit room is still
   * connected — the AI can keep speaking; we just stop sending uplink audio.
   * Reset on every connect/disconnect. Independent of `status`.
   */
  isMicMuted: boolean;
  connect: (driverPhone: string) => Promise<void>;
  disconnect: (opts?: { userInitiated?: boolean }) => void;
  setMicMuted: (muted: boolean) => Promise<void>;
  sendText: (text: string) => Promise<boolean>;
}

export const useVoiceSessionStore = create<VoiceSessionState>((set, get) => {
  // Shared by the real RoomEvent.Disconnected listener and the watchdog
  // below — both need to do the exact same teardown, the only difference is
  // *how* they found out the room is gone (a clean event vs. polling
  // discovering it's already dead). `guardRoom` is the specific `Room`
  // instance that detected the problem — skipped if a *newer* room has
  // since replaced the module-level `room` (a fresh connect() already
  // superseded this one, so tearing down would clobber the new session).
  const handleDisconnected = async (guardRoom: Room) => {
    if (room !== guardRoom) {
      bind({ room: guardRoom.name || "-" });
      devlog.event("voice_disconnect", {
        ok: true,
        skipped: true,
        reason: "room_replaced",
      });
      return;
    }
    bind({ room: guardRoom.name || "-" });
    devlog.event("voice_disconnect", { ok: true, reason: "teardown" });
    room = null;
    clearWatchdog();
    audioEls.forEach((el) => el.remove());
    audioEls.clear();
    // Awaited, not fire-and-forget — `status` used to flip to 'idle' before
    // the mic was actually released, so wake-word's own resume logic (which
    // watches for `status === 'idle'`) could only guess how long to wait
    // before it was safe to grab the mic again. Now that `idle` only fires
    // once LiveKit's audio session has genuinely torn down, that handoff is
    // both faster and doesn't depend on the guess being long enough.
    await stopAudioSession();
    clearLogContext();
    stopCallForegroundService();
    stopConnectingFiller();
    set({
      status: "idle",
      agentAudioLevel: 0,
      isCallActive: false,
      callMode: "",
      agentSpeaking: false,
      isMicMuted: false,
    });
    if (pendingUserDisconnectFiller) {
      pendingUserDisconnectFiller = false;
      try {
        await playDisconnectingFiller();
      } finally {
        stopDisconnectingFiller();
      }
    } else {
      stopDisconnectingFiller();
    }
  };

  const connectWithToken = async (
    getToken: () => Promise<{ token: string; livekit_url: string }>,
  ) => {
    // Synchronous re-entrancy guard — see `connecting`'s own comment for why
    // the `room`-based staleness check below isn't enough on its own.
    if (connecting) {
      devlog.event("voice_connect", {
        ok: true,
        skipped: true,
        reason: "already_in_flight",
      });
      return;
    }
    connecting = true;
    try {
      await connectWithTokenLocked(getToken);
    } finally {
      connecting = false;
    }
  };

    const connectWithTokenLocked = async (
    getToken: () => Promise<{ token: string; livekit_url: string }>,
  ) => {
    const connectStartedAt = Date.now();
    // A stale room can be left behind if the app was backgrounded and the
    // connection died without ever firing RoomEvent.Disconnected (Android
    // suspends WebRTC threads while the app isn't in the foreground) — treat
    // anything that isn't actively connected/connecting as dead and reconnect.
    if (room) {
      if (
        room.state === ConnectionState.Connected ||
        room.state === ConnectionState.Connecting
      )
        return;
      // Awaited — `disconnect()` is async (tears down the underlying
      // RTCPeerConnection/DTLS identity) and was previously fire-and-forget
      // here. Creating the new Room() below before the old peer connection
      // had actually finished disposing raced its teardown against the new
      // one's handshake — confirmed in production logs as a WebRTC "Local
      // fingerprint does not match identity" failure, and separately as
      // several overlapping peer connections (rn-webrtc pc ids incrementing
      // back-to-back within the same second) once rapid wake-word-triggered
      // reconnects piled up.
      await room.disconnect();
      room = null;
    }

    // Flip to 'connecting' immediately — spoken filler covers the handshake gap.
    set({
      status: "connecting",
      isCallActive: false,
      callMode: "",
      agentSpeaking: false,
      isMicMuted: false,
    });
    stopConnectingFiller();
    try {
      // Wake-word subscribe already stopListening() on `connecting`. Brief
      // settle so native AudioRecord can release before LiveKit publishes —
      // avoid dynamic-importing wakeWordService here (circular with this
      // store; Metro/Hermes then threw ReferenceError: Property 'Platform'
      // doesn't exist mid-connect).
      await new Promise<void>((resolve) => setTimeout(resolve, 350));
      // Filler during token fetch only — stop before LiveKit owns playAndRecord.
      // Calling startAudioSession twice (refreshVoiceAudioRoute) caused OSStatus -50 on iOS.
      const [{ token, livekit_url }, micPerm] = await Promise.all([
        getToken(),
        playConnectingFiller().then(() =>
          requestRecordingPermissionsAsync().catch(() => ({
            granted: false,
            status: "undetermined",
          })),
        ),
      ]);
      if (!micPerm.granted) {
        devlog.event("voice_mic", {
          ok: false,
          error: "permission_denied",
          detail: String(micPerm.status ?? "denied"),
        });
      }
      await handoffConnectingFillerForLiveKit();
      await startAudioSession();
      const r = new Room();
      room = r;

      // Backend publishes this whenever a real SIP-dialed call starts/ends
      // (bridge/agent-mediated/background) — see call_state.py. `payload` is
      // UTF-8 JSON, not a text-stream, so it's decoded manually here rather
      // than via registerTextStreamHandler.
      r.on(RoomEvent.DataReceived, (payload, _participant, _kind, topic) => {
        if (topic === CALL_STATE_TOPIC) {
          try {
            const msg = JSON.parse(new TextDecoder().decode(payload));
            if (msg?.type === "call_state") {
              set({
                isCallActive: !!msg.active,
                callMode:
                  msg.active && (msg.mode === "agent" || msg.mode === "bridge")
                    ? msg.mode
                    : "",
              });
            }
          } catch (err) {
            console.error(
              "[voice-session] failed to parse call_state payload",
              err,
            );
          }
          return;
        }
        if (topic === AGENT_STATE_TOPIC) {
          try {
            const msg = JSON.parse(new TextDecoder().decode(payload));
            if (msg?.type === "agent_state") {
              set({
                agentSpeaking:
                  msg.state === "speaking" || msg.state === "thinking",
              });
            }
          } catch (err) {
            console.error(
              "[voice-session] failed to parse agent_state payload",
              err,
            );
          }
        }
      });

      r.on(RoomEvent.TrackSubscribed, (track, publication, participant) => {
        if (track.kind !== Track.Kind.Audio) return;
        if (participant?.identity === r.localParticipant.identity) return;
        devlog.event("voice_agent_track", {
          ok: true,
          participant: participant?.identity ?? "-",
          source: String(publication?.source ?? "-"),
        });
        if (Platform.OS === "web") {
          const audioEl = track.attach() as HTMLAudioElement;
          audioEls.add(audioEl);
          document.body.appendChild(audioEl);
        }
        // Native: subscribed audio tracks play automatically through the
        // active AudioSession — no manual attach step needed.
      });

      r.on(RoomEvent.TrackUnsubscribed, (track) => {
        if (track.kind !== Track.Kind.Audio) return;
        if (Platform.OS === "web") {
          track.detach().forEach((el) => {
            audioEls.delete(el as HTMLAudioElement);
            (el as HTMLAudioElement).remove();
          });
        }
      });

      r.on(RoomEvent.Disconnected, (reason) => {
        devlog.event("voice_disconnect", { ok: true, reason: String(reason) });
        handleDisconnected(r);
      });

      // Drives the assistant orb's shape from the AI's actual voice loudness
      // instead of a fixed animation — fires ~every 200ms with the current
      // speakers sorted by level. The agent is whichever participant isn't us.
      r.on(RoomEvent.ActiveSpeakersChanged, (speakers) => {
        const agent = speakers.find(
          (p) => p.identity !== r.localParticipant.identity,
        );
        set({ agentAudioLevel: agent?.audioLevel ?? 0 });
      });

      // Both the driver's own speech-to-text and the agent's replies arrive on
      // the same topics — distinguish by participant identity, not by topic.
      const recentMessages = new Map<string, number>();
      const handleStream = async (
        reader: Parameters<Parameters<Room["registerTextStreamHandler"]>[1]>[0],
        participantInfo: { identity: string },
      ) => {
        const isLocal =
          participantInfo.identity === r.localParticipant.identity;
        const isCustomerSip =
          get().isCallActive &&
          /^customer-/i.test(participantInfo.identity);
        const from: VoiceMessageSource = isLocal
          ? "user"
          : isCustomerSip
            ? "customer"
            : "agent";

        const segmentId = reader.info.attributes?.[SEGMENT_ID_ATTR];

        const emit = (text: string, isFinal: boolean) => {
          if (!text.trim()) return;
          if (from === "agent" && isRawToolToken(text)) return;
          if (isFinal) {
            const messageKey = transcriptDedupKey(from, text);
            const now = Date.now();
            const previousTimestamp = recentMessages.get(messageKey);
            if (previousTimestamp && now - previousTimestamp < 3000) return;
            recentMessages.set(messageKey, now);
            for (const [key, timestamp] of recentMessages) {
              if (now - timestamp >= 3000) recentMessages.delete(key);
            }
            devlog.event("voice_transcript", { from, text: text.trim() });
            if (
              get().callMode === "bridge" &&
              from === "customer" &&
              r.localParticipant
            ) {
              r.localParticipant
                .publishData(
                  new TextEncoder().encode(
                    JSON.stringify({ speaker: "customer", text: text.trim() }),
                  ),
                  { reliable: true, topic: CALL_TRANSCRIPT_TOPIC },
                )
                .catch((err) =>
                  console.warn("[voice-session] call_transcript publish failed", err),
                );
            }
          }
          messageListeners.forEach((listener) =>
            listener(text, from, { isFinal, segmentId }),
          );
        };

        // Typed chat is one complete payload. Transcriptions are a live
        // delta stream (agent TTS tokens, STT hypotheses) — readAll() would
        // hide every chunk until the segment closed, so the bubble jumped
        // from empty to a finished sentence.
        if (reader.info.topic !== TRANSCRIPTION_TOPIC) {
          emit(await reader.readAll(), true);
          return;
        }

        let text = "";
        for await (const chunk of reader) {
          text += chunk;
          emit(text, false);
        }
        emit(text, isFinalTranscriptStream(reader));
      };
      r.registerTextStreamHandler(TRANSCRIPTION_TOPIC, handleStream);
      r.registerTextStreamHandler(CHAT_TOPIC, handleStream);

      // Lets the backend voice agent ask this device to search the driver's
      // own phone contacts by name — contacts only exist on-device, the
      // agent has no other way to reach them. See contactsSearch.ts and the
      // backend's find_contact tool (app/voicebot/vn/tools/find_contact.py).
      // Errors are caught and returned as a JSON `{error}` string rather than
      // thrown — a thrown error only surfaces to the Python caller as an
      // opaque generic "Application Error", losing the actual reason.
      r.registerRpcMethod("search_contacts", async (data) => {
        try {
          const { query } = JSON.parse(data.payload);
          const matches = await searchContacts(query);
          return JSON.stringify({ matches });
        } catch (err) {
          return JSON.stringify({
            error: err instanceof Error ? err.message : String(err),
          });
        }
      });

      await r.connect(livekit_url, token);
      bind({ room: r.name || "-", conv: r.name || "-" });
      await r.localParticipant.setMicrophoneEnabled(true);
      let micPub = r.localParticipant.getTrackPublication(Track.Source.Microphone);
      // One remic retry if publish succeeded as muted/missing — common after
      // filler/Vosk handoff left AVAudioSession shared on iOS.
      if (!micPub || micPub.isMuted) {
        await r.localParticipant.setMicrophoneEnabled(false);
        await new Promise<void>((resolve) => setTimeout(resolve, 200));
        await r.localParticipant.setMicrophoneEnabled(true);
        micPub = r.localParticipant.getTrackPublication(Track.Source.Microphone);
      }
      devlog.event("voice_mic", {
        ok: !!micPub && !micPub.isMuted,
        muted: !!micPub?.isMuted,
        has_publication: !!micPub,
      });
      await startCallForegroundService();
      set({ status: "connected", isMicMuted: false });
      devlog.event("voice_connect", {
        ok: true,
        duration_ms: Date.now() - connectStartedAt,
      });

      clearWatchdog();
      watchdogTimer = setInterval(() => {
        if (room !== r) {
          clearWatchdog();
          return;
        }
        // `r.state` is the room's own live WebRTC connection state — checked
        // directly rather than trusting `status` to already reflect it,
        // since that's exactly what a partial failure (a data channel dying
        // without RoomEvent.Disconnected ever firing) leaves stale.
        if (r.state === ConnectionState.Disconnected) {
          handleDisconnected(r);
        }
      }, WATCHDOG_INTERVAL_MS);
    } catch (err) {
      // The driver cancelling mid-connect (disconnect() called while r.connect()
      // was still in flight — see the store's own `disconnect`) surfaces here
      // as this specific, expected rejection, not as a real connection
      // failure. Treating it as one used to flip `status` to 'error', which
      // (a) reads as a broken connection to the driver even though they just
      // cancelled on purpose, and (b) left this catch's cleanup racing the
      // *next* connect attempt: `stopAudioSession()`/`room.disconnect()`
      // below were fire-and-forget, so a fast reconnect (wake-word retrying,
      // or the driver tapping the orb again) could call `startAudioSession()`
      // /create a new Room before the cancelled attempt's teardown had
      // actually finished — this is what produced the observed "connects
      // this session, but the previous one turns on instead" symptom and the
      // cascading WebRTC errors (negotiation timeout, "Cannot read property
      // 'client' of undefined") on the next attempt.
      const cancelled =
        err instanceof ConnectionError &&
        err.reason === ConnectionErrorReason.Cancelled;
      if (cancelled) {
        devlog.event("voice_connect", { ok: true, cancelled: true });
      } else {
        devlog.event("voice_connect", {
          ok: false,
          error: err instanceof Error ? err.name : "unknown",
          detail: err instanceof Error ? err.message : String(err),
          duration_ms: Date.now() - connectStartedAt,
        });
      }
      clearWatchdog();
      try {
        await room?.disconnect();
      } catch {
        // ignore teardown races during failed connect
      }
      room = null;
      await stopAudioSession();
      stopCallForegroundService();
      stopConnectingFiller();
      stopDisconnectingFiller();
      set({
        status: cancelled ? "idle" : "error",
        agentAudioLevel: 0,
        isCallActive: false,
        callMode: "",
        agentSpeaking: false,
        isMicMuted: false,
      });
    }
  };

  return {
    status: "idle",
    agentAudioLevel: 0,
    isCallActive: false,
    callMode: "",
    agentSpeaking: false,
    isMicMuted: false,

    connect: (driverPhone: string) =>
      connectWithToken(() =>
        voiceService.getDriverToken(driverPhone, getVoiceRoutingLang()),
      ),

    // The AI button in the tab bar must gate its own hangup on `isCallActive`
    // before calling this — see AssistantTabButton.tsx's handlePress.
    // `disconnect()` itself stays unconditional (also used for cleanup paths
    // like unmount/logout that must always be able to tear the room down).
    disconnect: (opts?: { userInitiated?: boolean }) => {
      void (async () => {
        const { status } = get();
        const userHangup = !!(
          opts?.userInitiated &&
          (status === "connected" || status === "connecting")
        );
        pendingUserDisconnectFiller = userHangup;
        pendingClosePanelOnIdle = userHangup;
        stopConnectingFiller();
        await room?.disconnect();
      })();
    },

    setMicMuted: async (muted: boolean) => {
      if (!room || get().status !== "connected") return;
      try {
        await room.localParticipant.setMicrophoneEnabled(!muted);
        set({ isMicMuted: muted });
      } catch (err) {
        devlog.event("voice_mic", {
          ok: false,
          error: err instanceof Error ? err.name : "unknown",
          detail: err instanceof Error ? err.message : String(err),
        });
      }
    },

    sendText: async (text: string) => {
      if (!room || get().status !== "connected") return false;
      await room.localParticipant.sendText(text, { topic: CHAT_TOPIC });
      return true;
    },
  };
});

/** Subscribe to transcribed/chat messages from the active voice session. Returns an unsubscribe fn. */
export function subscribeVoiceMessages(
  listener: VoiceMessageListener,
): () => void {
  messageListeners.add(listener);
  return () => messageListeners.delete(listener);
}

/** True once after user hang-up — chat should close when status hits idle. */
export function consumeClosePanelOnVoiceIdle(): boolean {
  const v = pendingClosePanelOnIdle;
  pendingClosePanelOnIdle = false;
  return v;
}
