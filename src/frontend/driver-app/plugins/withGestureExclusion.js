const { withMainActivity } = require('@expo/config-plugins')

// Android's gesture-navigation mode (no 3-button nav bar) reserves ~20-40dp
// along the screen's left/right edges for the system back-swipe gesture.
// LiquidGlassTabBar's floating pill-bar sits BAR_SIDE_MARGIN=20dp from those
// edges (src/components/LiquidGlassTabBar.tsx) — close enough that the outer
// rim of the first (Home) and last (Profile) tab falls inside that reserved
// zone, so a tap there gets intercepted by the OS gesture recognizer before
// the app's own touch handling (GestureDetector) ever sees it. Confirmed:
// only reproduces on devices using gesture navigation, not 3-button nav, and
// only at the two outer edges — the pill still shows a nearby touch "arriving"
// there, but the actual tabPress/navigate never fires.
//
// `View.setSystemGestureExclusionRects()` (API 29+) tells the OS "hand these
// specific pixels to the app instead" — there's no equivalent JS-only fix,
// so this runs as a config plugin injecting a small block into MainActivity.kt
// (regenerated by `expo prebuild`, hence the plugin instead of hand-editing
// the generated file directly).
//
// Keep the 20 / 16 / 76 numbers below in sync with BAR_SIDE_MARGIN /
// BAR_BOTTOM_MARGIN / CONTENT_HEIGHT in LiquidGlassTabBar.tsx if any of them
// ever change — they describe the same floating bar's geometry.
const MARKER = '[withGestureExclusion]'

const EXCLUSION_KOTLIN = `
    // ${MARKER} — see plugins/withGestureExclusion.js for why this exists.
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
      window.decorView.post {
        val density = resources.displayMetrics.density
        val screenWidth = resources.displayMetrics.widthPixels
        val screenHeight = resources.displayMetrics.heightPixels
        val exclusionWidthPx = (40 * density).toInt()
        val barBottomMarginPx = (16 * density).toInt()
        val barHeightPx = (76 * density).toInt()
        val barTop = screenHeight - barBottomMarginPx - barHeightPx
        val barBottom = screenHeight - barBottomMarginPx
        window.decorView.systemGestureExclusionRects = listOf(
          android.graphics.Rect(0, barTop, exclusionWidthPx, barBottom),
          android.graphics.Rect(screenWidth - exclusionWidthPx, barTop, screenWidth, barBottom)
        )
      }
    }`

function withGestureExclusion(config) {
  return withMainActivity(config, config => {
    const src = config.modResults
    if (src.language !== 'kt') {
      throw new Error(`withGestureExclusion: expected a Kotlin MainActivity, got "${src.language}" — this plugin needs updating for Java.`)
    }
    if (src.contents.includes(MARKER)) {
      return config // already injected — idempotent across repeated prebuilds
    }
    if (!src.contents.includes('super.onCreate(null)')) {
      throw new Error('withGestureExclusion: could not find "super.onCreate(null)" in MainActivity.kt to anchor the injection.')
    }
    src.contents = src.contents.replace(
      'super.onCreate(null)',
      `super.onCreate(null)\n${EXCLUSION_KOTLIN}`,
    )
    return config
  })
}

module.exports = withGestureExclusion
